#!/usr/bin/env python3
"""Build a curated Library list for the Pianomi menu bar app.

The Kunstderfuge piano-solo dump is ~2.5k files across 45 composers, most of
them obscure (Alkan, Dussek, Raff, Busoni...). Browsing that from a menu is
hopeless, so this script writes a small text file listing only the composers a
general audience would recognise, plus every file that is *not* in the catalog
at all — i.e. the songs you added yourself, which are always kept.

Output format, one line per song:

    <Group><TAB><filename>

`Pianomi` reads it through `[library] allowlist` in the config. The grouping
column is why this is not just a filename list: the catalog knows the real
composer, while the filenames only start with the *work* (`preludes_...`,
`sonata_...`), which makes prefix grouping useless.

Usage:
    python3 tools/build_library_list.py \
        --catalog ~/Documents/MIDI-Piano-Klasifikasi/katalog-piano-solo-kunstderfuge.csv \
        --dir     ~/Documents/MIDI-Piano-Klasifikasi/Piano-Solo \
        --out     ~/Documents/MIDI-Piano-Klasifikasi/library-famous.txt
"""

import argparse
import csv
import os
import sys
import unicodedata

# Composers worth showing, keyed by the name the catalog uses. The value is the
# group label; surnames only, because that is what people look for.
FAMOUS = {
    "Fryderyk Chopin": "Chopin",
    "Ludwig van Beethoven": "Beethoven",
    "Wolfgang Amadeus Mozart": "Mozart",
    "Johann Sebastian Bach": "Bach",
    "Franz Schubert": "Schubert",
    "Robert Schumann": "Schumann",
    "Johannes Brahms": "Brahms",
    "Franz Liszt": "Liszt",
    "Claude Debussy": "Debussy",
    "Maurice Ravel": "Ravel",
    "Aleksander Scriabin": "Scriabin",
    "Edvard Hagerup Grieg": "Grieg",
    "Pyotr Ilyich Tchaikovsky": "Tchaikovsky",
    "Modest Mussorgsky": "Mussorgsky",
    "Felix Mendelssohn-Bartholdy": "Mendelssohn",
    "Isaac Albeniz": "Albeniz",
    "Erik Satie": "Satie",
    "Camille Saint-Saëns": "Saint-Saens",
    "Antonin Dvorak": "Dvorak",
    "Gabriel Fauré": "Faure",
    "Bela Bartok": "Bartok",
    "Sergei Prokofiev": "Prokofiev",
    "Dimitri Shostakovich": "Shostakovich",
    "George Gershwin": "Gershwin",
    "Muzio Clementi": "Clementi",
    "Georges Bizet": "Bizet",
    # The catalog lumps these under "various composers"; the files themselves
    # are all Joplin rags, which are certainly famous.
    "(Berbagai penggubah ragtime)": "Joplin",
}

MINE = "Mine"


def read_catalog(path):
    """filename -> catalog composer name."""
    out = {}
    with open(path, encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            name = (row.get("nama_file_situs") or "").strip()
            composer = (row.get("komposer") or "").strip()
            if name:
                out[name] = composer
    return out


def ascii_safe(text):
    """Group labels are menu items; keep them in plain ASCII."""
    norm = unicodedata.normalize("NFKD", text)
    return norm.encode("ascii", "ignore").decode("ascii")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", required=True)
    ap.add_argument("--dir", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    catalog = read_catalog(args.catalog)
    try:
        names = [f for f in os.listdir(args.dir) if f.lower().endswith((".mid", ".midi"))]
    except OSError as e:
        sys.exit(f"cannot read {args.dir}: {e}")

    rows = []
    dropped = {}
    mine = 0
    for name in sorted(names, key=str.lower):
        if name not in catalog:
            rows.append((MINE, name))
            mine += 1
            continue
        composer = catalog[name]
        group = FAMOUS.get(composer)
        if group is None:
            dropped[composer] = dropped.get(composer, 0) + 1
            continue
        rows.append((ascii_safe(group), name))

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("# <Group>\\t<filename> — generated by tools/build_library_list.py\n")
        f.write("# Edit freely: delete lines to hide a song, add lines to show one.\n")
        for group, name in rows:
            f.write(f"{group}\t{name}\n")

    kept = len(rows) - mine
    print(f"kept {kept} catalogued + {mine} of your own = {len(rows)} songs")
    print(f"hid {sum(dropped.values())} files from {len(dropped)} composers:")
    for composer, n in sorted(dropped.items(), key=lambda kv: -kv[1]):
        print(f"  {n:5d}  {composer}")
    print(f"\nwritten to {args.out}")


if __name__ == "__main__":
    main()
